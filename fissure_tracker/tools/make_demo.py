"""
Demo data for the video, screenshots and the submission's trace example.

Builds a local store (outputs/store, wiped first) with a few weeks of history:
  crack #1  slowly widening; this week's photo -> close-up requested -> close-up -> engineer review
  crack #2  stable for 5 weeks
  crack #3  this week's photo was blurry -> retake requested
Photos are synthetic (a rendered wall seen by a virtual camera). Dates are spread over past weeks.
Also writes docs/trace_example.md: the full agent trace of crack #1's case.

    python tools/make_demo.py          rules backup decides
    python tools/make_demo.py --ai     Amazon Nova decides (needs Bedrock access), rules as backup
Then: python serve_local.py  ->  http://localhost:8000/cracks?code=demo
"""

import json
import os
import shutil
import sys
from datetime import datetime, timedelta, timezone

import cv2

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [ROOT, os.path.join(ROOT, "tests")]

from agent import OUTPUT_DIR, LocalNotifier, handle_photo, make_llm  # noqa: E402
from store import LocalStore  # noqa: E402
from synthetic import crack_drawer, crack_path, make_photo  # noqa: E402

WALL, IMAGE = (420.0, 320.0), (1600, 1200)
CENTRE = (WALL[0] / 2, WALL[1] / 2)


def photo(marker_id, width_mm, seed, px_per_mm=4.0, tilt_deg=0.0, blur_sigma=0.0):
    points = crack_path((CENTRE[0] - 50, CENTRE[1] + 45), 100, seed=marker_id)
    draw, _ = crack_drawer(points, width_mm)
    img, _ = make_photo(marker_id=marker_id, tilt_deg=tilt_deg, distance_mm=0.72 * max(IMAGE) / px_per_mm,
                        image_size=IMAGE, render_px_per_mm=12, wall_mm=WALL, draw=draw, seed=seed, blur_sigma=blur_sigma)
    return cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, 92])[1].tobytes()


def backdate(store, case, when):
    """Move a case (and its readings) to `when`, keeping the gaps between its steps."""
    first = datetime.fromisoformat(case["created"])
    shift = when - first

    def move(iso):
        return (datetime.fromisoformat(iso) + shift).isoformat(timespec="milliseconds")
    case["created"], case["updated"] = move(case["created"]), move(case["updated"])
    for item in case["photos"] + case["trace"]:
        item["time"] = move(item["time"])
    for key in ("review",):
        if case.get(key):
            case[key]["requested"] = move(case[key]["requested"])
    if case.get("reading"):
        case["reading"]["time"] = move(case["reading"]["time"])
    store.put_case(case)
    rows = [json.loads(line) for line in open(store.readings_file, encoding="utf-8")]
    for r in rows:
        if r["case_id"] == case["case_id"]:
            r["time"] = move(r["time"])
    with open(store.readings_file, "w", encoding="utf-8") as f:
        f.writelines(json.dumps(r) + "\n" for r in rows)


def trace_markdown(case):
    lines = [f"# Agent trace example: crack #{case['marker_id']}",
             "",
             "Generated by `python tools/make_demo.py`. One case, two photos. Each step is a tool call; "
             "`decided_by` says who chose it. **Note how OpenCV's output changes the next call**: after "
             "`compare_with_history` reports growth with a coarse measurement, the agent asks for a close-up "
             "instead of saving; after the close-up confirms it, it asks an engineer.",
             ""]
    for s in case["trace"]:
        lines.append(f"### {s['step']}. `{s['tool']}` — decided by {s['decided_by']} (photo {s['photo_id']})")
        if s.get("thought"):
            lines.append(f"> {s['thought']}")
        if s["input"]:
            lines.append(f"Input: `{json.dumps(s['input'])}`")
        lines += ["", "```json", json.dumps(s["output"], indent=1), "```", ""]
    lines.append(f"**Final status:** {case['status']}  \n**Message to the owner:** {case['owner_message']}")
    return "\n".join(lines) + "\n"


def main():
    folder = os.path.join(OUTPUT_DIR, "store")
    shutil.rmtree(folder, ignore_errors=True)
    store, mail = LocalStore(folder), LocalNotifier()
    if "--ai" in sys.argv:
        os.environ["AGENT_MODE"] = "auto"
        llm = make_llm()
    else:
        llm = None
    today = datetime.now(timezone.utc).replace(hour=4, minute=30, second=0, microsecond=0)   # 10:00 IST

    def run(data, week, case_id=None, minutes=0):
        case = handle_photo(store, data, case_id, mail, llm, base_url="http://localhost:8000")
        if case_id is None:
            backdate(store, case, today - timedelta(weeks=week) + timedelta(minutes=minutes))
        else:
            first_time = datetime.fromisoformat(case["created"])
            fresh = store.get_case(case["case_id"])        # the newest photo and steps still carry today's time
            latest = max(datetime.fromisoformat(p["time"]) for p in fresh["photos"])
            shift = first_time + timedelta(minutes=minutes) - latest
            for item in fresh["photos"] + fresh["trace"]:
                t = datetime.fromisoformat(item["time"])
                if t > first_time + timedelta(hours=1):
                    item["time"] = (t + shift).isoformat(timespec="milliseconds")
            fresh["updated"] = fresh["trace"][-1]["time"]
            if fresh.get("review"):
                fresh["review"]["requested"] = fresh["updated"]
            rows = [json.loads(line) for line in open(store.readings_file, encoding="utf-8")]
            for r in rows:
                if r["case_id"] == fresh["case_id"] and datetime.fromisoformat(r["time"]) > first_time + timedelta(hours=1):
                    r["time"] = (datetime.fromisoformat(r["time"]) + shift).isoformat(timespec="milliseconds")
            with open(store.readings_file, "w", encoding="utf-8") as f:
                f.writelines(json.dumps(r) + "\n" for r in rows)
            store.put_case(fresh)
            case = fresh
        print(f"  week -{week}: {case['status']:<22} {case['owner_message'][:80]}")
        return case

    print("crack #2 (stable)")
    for week, tilt in zip(range(5, 0, -1), (0, 8, -6, 4, -3)):
        run(photo(2, 0.8, seed=2, px_per_mm=6, tilt_deg=tilt), week, minutes=10)
    print("crack #1 (growing)")
    for week, (width, tilt) in zip(range(5, 0, -1), ((1.0, 0), (1.0, 6), (1.1, -5), (1.2, 3), (1.3, -4))):
        run(photo(1, width, seed=1, tilt_deg=tilt), week)
    case = run(photo(1, 1.9, seed=1, tilt_deg=5), 0)
    case = run(photo(1, 1.9, seed=1, px_per_mm=10), 0, case["case_id"], minutes=6)
    print("crack #3 (blurry photo this week)")
    run(photo(3, 0.6, seed=3, px_per_mm=6), 3, minutes=20)
    run(photo(3, 0.6, seed=3, px_per_mm=6, blur_sigma=3), 0, minutes=20)

    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "trace_example.md"), "w", encoding="utf-8") as f:
        f.write(trace_markdown(case))
    print(f"\nEngineer e-mail (local):\n{mail.sent[-1]['body'] if mail.sent else '(none)'}")
    print("\nWrote outputs/store and docs/trace_example.md. Run: python serve_local.py")


if __name__ == "__main__":
    main()
